//! Share training state without changing the public tree or its combo order.

use std::collections::HashMap;

use super::{BoardData, Card, GameTree, NodeKind, Range, NONE, NO_CHILD, NUM_CARDS};
use crate::cards::{card_mask, suit};
use crate::game::ChanceOrbit;
use crate::iso::apply_suit_perm;
use crate::range::combo_index;
use crate::terminal::Hand;

type Permutation = [u8; 4];
type ComboMaps = [Vec<u32>; 2];
type HandPairs = [Vec<(u32, u32)>; 2];
const IDENTITY: Permutation = [0, 1, 2, 3];

#[derive(Debug)]
struct BoardSymmetry {
    representative: [Card; NUM_CARDS],
    orbits: Vec<ChanceOrbit>,
    hands: HandPairs,
}

#[derive(Debug)]
pub(super) struct SuitIso {
    by_board: Vec<Option<BoardSymmetry>>,
    aliases: Vec<(u32, u32)>,
    maps: Vec<ComboMaps>,
    pub(super) shared_decisions: usize,
}

fn permute_hand(hand: Hand, perm: &Permutation) -> usize {
    combo_index(apply_suit_perm(hand.0, perm), apply_suit_perm(hand.1, perm))
}

fn slot(board: &BoardData, player: usize, index: usize) -> u32 {
    board.indices[player].binary_search(&(index as u32)).expect("symmetric live combo") as u32
}

fn visible_suits(board: &BoardData) -> u8 {
    board.board.iter().fold(0, |mask, &card| mask | (1 << suit(card)))
}

fn swap(a: u8, b: u8) -> Permutation {
    let mut perm = IDENTITY;
    perm.swap(a as usize, b as usize);
    perm
}

impl BoardSymmetry {
    fn new(board: &BoardData, permutations: &[Permutation]) -> Option<Self> {
        let visible = visible_suits(board);
        let permitted: Vec<_> = permutations.iter().filter(|perm| {
            (0..4).all(|s| visible & (1 << s) == 0 || perm[s] as usize == s)
        }).collect();
        if permitted.len() < 2 {
            return None;
        }

        let representative = std::array::from_fn(|card| {
            permitted.iter().map(|perm| apply_suit_perm(card as Card, perm)).min().unwrap()
        });
        let hands = std::array::from_fn(|p| {
            board.hands[p].iter().enumerate().filter_map(|(i, &hand)| {
                let canonical = permitted.iter().map(|perm| permute_hand(hand, perm)).min().unwrap();
                (canonical != board.indices[p][i] as usize).then(|| (i as u32, slot(board, p, canonical)))
            }).collect()
        });

        let mut orbits: Vec<ChanceOrbit> = Vec::new();
        if board.board.len() < 5 {
            let mask = crate::cards::mask_of(&board.board);
            let mut group = [usize::MAX; NUM_CARDS];
            for (outcome, card) in (0..NUM_CARDS as Card).filter(|&c| mask & card_mask(c) == 0).enumerate() {
                let rep = representative[card as usize];
                if rep == card {
                    group[rep as usize] = orbits.len();
                    orbits.push(ChanceOrbit { outcome, aliases: Vec::new() });
                } else {
                    let perm = swap(suit(rep), suit(card));
                    let maps = std::array::from_fn(|p| {
                        board.hands[p].iter().filter(|h| h.0 != rep && h.1 != rep)
                            .map(|&h| slot(board, p, permute_hand(h, &perm))).collect()
                    });
                    orbits[group[rep as usize]].aliases.push(maps);
                }
            }
        }
        Some(Self { representative, orbits, hands })
    }
}

impl SuitIso {
    pub(super) fn new(tree: &GameTree, boards: &[BoardData], node_board: &[u32], ranges: &[Range; 2]) -> Option<Self> {
        let root = &boards[0];
        let visible = visible_suits(root);
        let mut interchangeable = [[false; 4]; 4];
        for a in 0..4u8 {
            interchangeable[a as usize][a as usize] = true;
            for b in a + 1..4 {
                if visible & ((1 << a) | (1 << b)) != 0 {
                    continue;
                }
                let perm = swap(a, b);
                let valid = ranges.iter().enumerate().all(|(p, range)| {
                    root.hands[p].iter().zip(&root.indices[p]).all(|(&h, &idx)| {
                        range.weight(idx as usize) == range.weight(permute_hand(h, &perm))
                    })
                });
                interchangeable[a as usize][b as usize] = valid;
                interchangeable[b as usize][a as usize] = valid;
            }
        }

        // All permutations generated by transpositions that preserve both ranges.
        let mut permutations = Vec::new();
        for a in 0..4u8 {
            for b in (0..4).filter(|&b| b != a) {
                for c in (0..4).filter(|&c| c != a && c != b) {
                    let perm = [a, b, c, 6 - a - b - c];
                    if perm.iter().enumerate().all(|(i, &j)| interchangeable[i][j as usize]) {
                        permutations.push(perm);
                    }
                }
            }
        }
        if permutations.len() < 2 || root.board.len() == 5 {
            return None;
        }

        let by_board: Vec<_> = boards.iter().map(|b| BoardSymmetry::new(b, &permutations)).collect();
        let mut aliases = vec![(NONE, NONE); tree.len()];
        let mut maps = Vec::new();
        let mut cache = HashMap::new();
        let mut shared_decisions = 0;
        let mut pending = vec![(tree.root(), tree.root(), IDENTITY)];
        while let Some((node, rep, perm)) = pending.pop() {
            let b = node_board[node as usize] as usize;
            let r = node_board[rep as usize] as usize;
            match (&tree.node(node).kind, &tree.node(rep).kind) {
                (NodeKind::Decision { actions, .. }, NodeKind::Decision { actions: rep_actions, .. }) => {
                    if node != rep {
                        let map = *cache.entry((b, r, perm)).or_insert_with(|| {
                            let id = maps.len() as u32;
                            maps.push(std::array::from_fn(|p| {
                                boards[b].hands[p].iter().map(|&h| slot(&boards[r], p, permute_hand(h, &perm))).collect()
                            }));
                            id
                        });
                        aliases[node as usize] = (rep, map);
                        shared_decisions += 1;
                    }
                    for (action, representative) in actions.iter().zip(rep_actions) {
                        pending.push((action.child, representative.child, perm));
                    }
                }
                (NodeKind::Chance { child_for_card, .. }, NodeKind::Chance { child_for_card: rep_child, .. }) => {
                    for (card, &child) in child_for_card.iter().enumerate().filter(|&(_, &c)| c != NO_CHILD) {
                        let mapped = apply_suit_perm(card as Card, &perm);
                        let canonical = by_board[r].as_ref().map_or(mapped, |board| board.representative[mapped as usize]);
                        let exchange = swap(suit(mapped), suit(canonical));
                        pending.push((child, rep_child[canonical as usize], perm.map(|s| exchange[s as usize])));
                    }
                }
                (NodeKind::Terminal(_), NodeKind::Terminal(_)) => {}
                _ => unreachable!("suit relabeling preserves the betting tree"),
            }
        }
        // A tree can end in forced all-in runouts, where there are no decisions to
        // share but folding the terminal work is still useful.
        Some(Self { by_board, aliases, maps, shared_decisions })
    }

    pub(super) fn orbits(&self, board: u32) -> Option<&[ChanceOrbit]> {
        self.by_board[board as usize].as_ref().map(|b| b.orbits.as_slice())
    }

    pub(super) fn alias(&self, node: u32, player: u8) -> Option<(u32, &[u32])> {
        let (rep, map) = self.aliases[node as usize];
        (rep != NONE).then(|| (rep, self.maps[map as usize][player as usize].as_slice()))
    }

    pub(super) fn hands(&self, board: u32, player: u8) -> &[(u32, u32)] {
        self.by_board[board as usize].as_ref().map_or(&[], |b| b.hands[player as usize].as_slice())
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::br::{self, StrategyProfile};
    use crate::cfr::{DcfrParams, Solver, StorageMode};
    use crate::config::{NodeLock, Sizings, SolveConfig, Tournament};
    use crate::game::Game;
    use crate::nlhe::NlheGame;
    use crate::solution::Solution;

    fn spot(board: &str) -> SolveConfig {
        let mut cfg = SolveConfig {
            board: board.into(), oop_range: "AA,KK,A4s,87s".into(), ip_range: "JJ,TT,KQs,76s".into(),
            effective_stack: 20.0, starting_pot: 6.0, raise_cap: 0,
            suit_isomorphism: true, ..SolveConfig::default()
        };
        cfg.sizings.oop.flop.bet = Sizings::new(&[50.0], false);
        cfg.sizings.oop.turn.bet = Sizings::new(&[50.0], false);
        cfg.sizings.oop.river.bet = Sizings::new(&[50.0], false);
        cfg
    }

    struct Expanded<'a>(&'a Solver<NlheGame>);

    impl StrategyProfile for Expanded<'_> {
        fn strategy_into(&self, node: u32, out: &mut [f32]) {
            self.0.average_strategy_into(node, out);
        }
    }

    #[test]
    fn folded_values_match_expanded_traversal_and_aliases_keep_their_board() {
        for (board, weight) in [("Qs Jh 2h", 0.0), ("Qs Jh 2h", 0.25), ("Qs Js 2s", 0.25)] {
            let mut cfg = spot(board);
            cfg.prediction_weight = weight;
            cfg.regret_startup_clip = board == "Qs Jh 2h" && weight > 0.0;
            let mode = if board == "Qs Js 2s" {
                cfg.tournament = Some(Tournament {
                    stacks: vec![20.0, 25.0, 18.0, 12.0], payouts: vec![50.0, 30.0, 20.0], seats: [0, 1],
                });
                StorageMode::I16
            } else {
                StorageMode::F32
            };
            let mut solver = Solver::new_configured(NlheGame::new(&cfg).unwrap(), mode, &cfg);
            let game = solver.game();
            let raw_entries: usize = game.tree().nodes().iter().enumerate().map(|(id, n)| {
                match &n.kind {
                    NodeKind::Decision { player, actions } => actions.len() * game.combo_count(id as u32, *player),
                    _ => 0,
                }
            }).sum();
            assert!(game.shared_suit_decisions() > 0);
            assert!(solver.storage_entries() < raw_entries);
            solver.run(10, &DcfrParams::default(), 0, |_, _, _| {});
            let game = solver.game();
            for hero in [0, 1] {
                let expanded = Expanded(&solver);
                let ev = br::expected_value(game, hero, &expanded);
                let best = br::best_response_value(game, hero, &expanded);
                assert!((solver.expected_value(hero) - ev).abs() < 2e-5, "{board}: EV");
                assert!((br::best_response_value(game, hero, &solver.average()) - best).abs() < 2e-5, "{board}: BR");
            }
            let alias = game.tree().resolve_line("check,check,7d,check,check,6c").unwrap();
            let (rep, slots) = game.strategy_alias(alias).expect("equivalent two-street branch");
            let displayed = game.board_at(alias);
            assert!(displayed.contains(&crate::cards::parse_card("7d").unwrap()));
            let probabilities = solver.average_strategy(alias);
            let canonical = solver.average_strategy(rep);
            for (a, b) in probabilities.chunks_exact(slots.len()).zip(canonical.chunks_exact(slots.len())) {
                for (&actual, &from) in a.iter().zip(slots) {
                    assert_eq!(actual.to_bits(), b[from as usize].to_bits());
                }
            }
            if board == "Qs Jh 2h" {
                let sol = Solution::from_solver(&solver, 0.0);
                assert_eq!(sol.format_version, if weight > 0.0 { 6 } else { 5 });
                let mut bytes = Vec::new();
                sol.to_writer(&mut bytes).unwrap();
                let reloaded = Solution::from_reader(bytes.as_slice()).unwrap();
                assert_eq!(reloaded, sol);
            }
        }
    }

    #[test]
    fn asymmetric_ranges_and_node_locks_keep_independent_subtrees() {
        let mut asymmetric = spot("Qs Jh 2h");
        asymmetric.oop_range = "AA,Ac4c".into();
        let game = NlheGame::new(&asymmetric).unwrap();
        assert_eq!(game.shared_suit_decisions(), 0);

        let mut locked = spot("Qs Jh 2h");
        locked.locks.push(NodeLock {
            line: "check,check,7c".into(), player: 0, freqs: Some(vec![1.0, 0.0]), strategy: None,
        });
        let game = NlheGame::new(&locked).unwrap();
        assert_eq!(game.shared_suit_decisions(), 0);
    }
}
